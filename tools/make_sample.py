#!/usr/bin/env python3
"""Generate a fully synthetic SaaS deals dataset (seeded, reproducible).

Writes:
  sample_data/sales_sample.csv   the dataset
  sample.js                      same CSV as a JS string, so the page works from file://

Planted patterns (so the dashboard has something to find):
  - EMEA is the strongest region, LATAM the weakest
  - Enterprise drives most of the revenue
  - The LATAM reps have low win rates
  - Marcus Webb's pipeline collapses in the last month
"""
import calendar
import csv
import json
import os
import random

random.seed(2026)
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

TEAM = {
    "North America": [("Priya Shah", 1.15), ("Jordan Lee", 1.0), ("Casey Morgan", 0.9)],
    "EMEA": [("Lena Fischer", 1.25), ("Amir Haddad", 1.1), ("Sofia Rossi", 1.0)],
    "APAC": [("Kenji Tanaka", 1.05), ("Marcus Webb", 1.0), ("Mei Lin", 0.95)],
    "LATAM": [("Diego Alvarez", 0.8), ("Tom Reyes", 0.55), ("Ana Costa", 0.75)],
}
REGION_FACTOR = {"North America": 1.0, "EMEA": 1.15, "APAC": 0.9, "LATAM": 0.7}
# product: (share of deals, min amount, max amount)
PRODUCTS = {
    "Starter": (0.30, 2500, 6000),
    "Pro": (0.35, 9000, 22000),
    "Enterprise": (0.12, 45000, 130000),
    "Analytics Add-on": (0.23, 1200, 4500),
}
YEAR = 2026
MONTHS = range(1, 11)  # Jan to Oct

names = list(PRODUCTS)
weights = [PRODUCTS[n][0] for n in names]

rows = []
for m in MONTHS:
    growth = 0.85 + 0.03 * m + random.uniform(-0.04, 0.04)
    days = calendar.monthrange(YEAR, m)[1]
    for region, reps in TEAM.items():
        for rep, skill in reps:
            n = round(random.randint(8, 13) * REGION_FACTOR[region] * growth)
            eff = skill
            if rep == "Marcus Webb" and m == 10:  # pipeline and win rate both collapse
                n = max(2, round(n * 0.2))
                eff = skill * 0.35
            for _ in range(n):
                prod = random.choices(names, weights)[0]
                _, lo, hi = PRODUCTS[prod]
                amount = int(round(random.uniform(lo, hi) / 50) * 50)
                won = random.random() < min(0.75, 0.42 * eff)
                status = "Closed Won" if won else "Closed Lost"
                if m == 10 and random.random() < 0.10:
                    status = "Open"
                day = random.randint(1, days)
                rows.append((f"{YEAR}-{m:02d}-{day:02d}", region, rep, prod, amount, status))

rows.sort()
os.makedirs(os.path.join(ROOT, "sample_data"), exist_ok=True)
csv_path = os.path.join(ROOT, "sample_data", "sales_sample.csv")
with open(csv_path, "w", newline="", encoding="utf-8") as f:
    w = csv.writer(f)
    w.writerow(["deal_id", "close_date", "region", "sales_rep", "product", "amount", "status"])
    for i, r in enumerate(rows, 1001):
        w.writerow([f"D-{i}", *r])

with open(csv_path, encoding="utf-8") as f:
    text = f.read()
with open(os.path.join(ROOT, "sample.js"), "w", encoding="utf-8") as f:
    f.write("/* Generated by tools/make_sample.py. Synthetic data. */\n")
    f.write("window.SAMPLE_CSV = " + json.dumps(text) + ";\n")

print(f"wrote {len(rows)} rows")
